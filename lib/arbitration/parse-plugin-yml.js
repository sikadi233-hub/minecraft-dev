/**
 * `plugin.yml` surgery for the merge step.
 *
 * The repository has no YAML dependency and is not going to grow one for five
 * generated keys, so this module is deliberately minimal: it owns two anchor
 * comments (`# [mc:commands]`, `# [mc:permissions]`) and replaces everything
 * between an anchor and the next top-level key with generated entries. The rest
 * of the file is never touched — a hand-written `description` or a `depend` list
 * survives untouched.
 *
 * The generated blocks are plain YAML with fixed shapes, which keeps the output
 * predictable enough to diff and to test without a parser.
 *
 * @module minecraft-dev/lib/arbitration/parse-plugin-yml
 */

/** Anchor for the generated `commands:` block. */
export const COMMANDS_ANCHOR = '# [mc:commands]'

/** Markers around the generated command block (idempotent replacement). */
export const COMMANDS_BEGIN = '# [mc:commands:begin]'
export const COMMANDS_END = '# [mc:commands:end]'

/** Anchor for the generated `permissions:` block. */
export const PERMISSIONS_ANCHOR = '# [mc:permissions]'

/** Markers around the generated permission block (idempotent replacement). */
export const PERMISSIONS_BEGIN = '# [mc:permissions:begin]'
export const PERMISSIONS_END = '# [mc:permissions:end]'

/** Whether the file still carries both anchors. */
export function hasPluginYmlAnchors(content) {
  const text = String(content)
  return text.includes(COMMANDS_ANCHOR) && text.includes(PERMISSIONS_ANCHOR)
}

/**
 * Render the `commands:` block (anchor line excluded).
 * @param {{ name: string, class?: string, permission?: string }[]} commands - merged commands.
 * @returns {string[]} YAML lines.
 */
export function renderCommandsBlock(commands) {
  if (commands.length === 0) return []
  const lines = ['commands:']
  for (const command of [...commands].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`  ${command.name}:`)
    lines.push(`    description: "${command.name} command (generated by minecraft-dev)"`)
    lines.push(`    usage: "/${command.name}"`)
    if (command.permission) lines.push(`    permission: ${command.permission}`)
  }
  return lines
}

/**
 * Render the `permissions:` block (anchor line excluded).
 * @param {{ node: string, default?: string }[]} permissions - merged permissions.
 * @returns {string[]} YAML lines.
 */
export function renderPermissionsBlock(permissions) {
  if (permissions.length === 0) return []
  const lines = ['permissions:']
  for (const permission of [...permissions].sort((a, b) => a.node.localeCompare(b.node))) {
    lines.push(`  ${permission.node}:`)
    lines.push(`    description: "generated by minecraft-dev"`)
    lines.push(`    default: ${String(permission.default ?? 'op').toLowerCase()}`)
  }
  return lines
}

/**
 * Replace the block between a begin/end marker pair, or create it after the
 * anchor on the first run. A plain "cut until the next top-level key" rule would
 * treat the generated `commands:` key as the end of the section and append a
 * second copy on the next merge.
 * @param {string[]} lines - file lines.
 * @param {string} anchor - anchor comment line.
 * @param {string} begin - begin marker.
 * @param {string} end - end marker.
 * @param {string[]} block - generated lines (empty to emit an empty section).
 * @returns {{ lines: string[], found: boolean }} updated lines.
 */
export function replaceSection(lines, anchor, begin, end, block) {
  const start = lines.findIndex(line => line.trim() === anchor)
  if (start < 0) return { lines, found: false }
  const beginAt = lines.findIndex(line => line.trim() === begin)
  const endAt = lines.findIndex(line => line.trim() === end)
  if (beginAt >= 0 && endAt > beginAt) {
    const next = [...lines.slice(0, beginAt), begin, ...block, end, ...lines.slice(endAt + 1)]
    return { lines: next, found: true }
  }
  // First run: keep the anchor, then the markers and the block.
  const next = [...lines.slice(0, start + 1), begin, ...block, end, ...lines.slice(start + 1)]
  return { lines: next, found: true }
}

/**
 * Merge commands and permissions into a `plugin.yml` body.
 * @param {object} options - content, commands, permissions.
 * @returns {{ content: string, missing: string[], commands: number, permissions: number }} result.
 */
export function mergePluginYml({ content, commands = [], permissions = [] }) {
  const missing = []
  let lines = String(content).split(/\r?\n/)
  if (lines.some(line => line.trim() === COMMANDS_ANCHOR)) {
    lines = replaceSection(lines, COMMANDS_ANCHOR, COMMANDS_BEGIN, COMMANDS_END, renderCommandsBlock(commands)).lines
  } else missing.push('commands')
  if (lines.some(line => line.trim() === PERMISSIONS_ANCHOR)) {
    lines = replaceSection(lines, PERMISSIONS_ANCHOR, PERMISSIONS_BEGIN, PERMISSIONS_END, renderPermissionsBlock(permissions)).lines
  } else missing.push('permissions')
  return { content: lines.join('\n'), missing, commands: commands.length, permissions: permissions.length }
}
